{
    return car >= 0 && car < 16 ? &specials[car] : NULL;
}

/* Constructor 8002d934 and weapon initialization 80033a50 use 32-bit unsigned
   multiplication/addition, including wrapping before the logical shift. */
uint32_t Tm3WeaponTimeTicks(uint32_t seconds_q12)
{
    return (seconds_q12 * 30u + 2048u) >> 12;
}

uint16_t Tm3WarthogDamage(uint32_t age)
{
    const Tm3ProjectileTuning* tuning = &projectiles[14];
    uint32_t product = (uint32_t)(int32_t)tuning->damage * (age << 12);
    uint32_t ramp = product / Tm3WeaponTimeTicks(tuning->lifetime_q12);
    return (uint16_t)((uint16_t)tuning->damage + ((ramp + 2048u) >> 12));
}
